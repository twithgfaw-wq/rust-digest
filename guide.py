def post(tg, text):
    """Публикуем гид и закрепляем без уведомления."""
    res = tg.send_message(text)
    mid = (res.get("result") or {}).get("message_id")
    if not mid:
        print("Гид не отправился:", res)
        return res
    pin = tg._post("pinChatMessage", {"chat_id": tg.chat, "message_id": mid,
                                      "disable_notification": "true"})
    print("Гид опубликован:", mid, "· закреплён:", pin.get("ok"),
          pin.get("description") or "")
    return res
